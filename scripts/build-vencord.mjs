// Bundles the core engine into the Vencord plugin and optionally copies the plugin into a
// Vencord source checkout. Usage: node scripts/build-vencord.mjs [--install <path to Vencord>]
import { build } from 'esbuild';
import { cp, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const pluginDir = resolve('vencord/uwuSpeak');
const banner = '// Generated by scripts/build-vencord.mjs from src/core. Do not edit.\n';

// Vencord does not ship unicode-segmenter or our JSON data, so inline everything into one module.
await build({
  entryPoints: ['src/core/index.ts'],
  outfile: join(pluginDir, 'engine.js'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  legalComments: 'inline',
  banner: { js: banner },
  plugins: [
    {
      // The engine only reads these fields; the descriptive ones would bloat Discord's bundle.
      name: 'slim-dictionary',
      setup(b) {
        b.onLoad({ filter: /data[\\/]emoticons\.json$/ }, async (args) => {
          const { version, entries } = JSON.parse(await readFile(args.path, 'utf8'));
          const keep = ['id', 'text', 'aliases', 'intents', 'intensity', 'styles', 'selection', 'eligibility'];
          const slim = entries.map((e) => Object.fromEntries(keep.map((k) => [k, e[k]])));
          return { contents: JSON.stringify({ version, entries: slim }), loader: 'json' };
        });
      },
    },
  ],
});
const types = await readFile('src/core/types.ts', 'utf8');
const mood = (await readFile('src/core/mood.ts', 'utf8')).match(
  /export interface LabelScore \{[^}]*\}/,
)[0];
await writeFile(
  join(pluginDir, 'engine.d.ts'),
  banner +
    types +
    mood +
    '\nexport declare const intents: string[];\n' +
    'export declare const MAX_INPUT: number;\n' +
    'export declare const miniLmCutoff: number;\n' +
    'export declare function convert(text: string, options?: ConversionOptions): ConversionResult;\n' +
    'export declare function intentsFromScores(\n' +
    '  scores: readonly LabelScore[],\n' +
    '  cutoff: number,\n' +
    '  positiveOnly?: boolean,\n' +
    '): string[];\n',
);
console.log(`Built ${pluginDir}`);

const flag = process.argv.indexOf('--install');
if (flag !== -1) {
  const vencord = process.argv[flag + 1];
  if (!vencord) throw new Error('--install needs the path to a Vencord source checkout.');
  const userplugins = join(resolve(vencord), 'src', 'userplugins');
  if (!(await stat(join(resolve(vencord), 'src')).catch(() => null))?.isDirectory())
    throw new Error(`${vencord} is not a Vencord source checkout (no src folder).`);
  const target = join(userplugins, 'uwuSpeak');
  await rm(target, { recursive: true, force: true });
  await cp(pluginDir, target, { recursive: true });
  console.log(`Installed to ${target}`);
}
